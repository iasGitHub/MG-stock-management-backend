-- V2 : alignement idempotent du schéma existant sur les entités JPA.
--
-- V1 couvre les bases fraîches. V2 ne s'applique qu'aux bases historiques
-- initialisées avant Flyway (baseline à la version 1) : il crée uniquement
-- ce qui manque (tables, colonnes, contraintes, index), sans jamais modifier
-- l'existant, afin que « ddl-auto: validate » passe sur un déploiement
-- antérieur à la refacto. Sur une base fraîche, tout est no-op.
--
-- La fonction _ensure_col est supprimée en fin de script.
-- ============================================================================

-- 1. Tables potentiellement absentes -----------------------------------------

CREATE TABLE IF NOT EXISTS users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             varchar(50),
    password             varchar(255),
    full_name            varchar(100),
    role                 varchar(20),
    active               boolean,
    must_change_password boolean
);

CREATE TABLE IF NOT EXISTS categories (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(50),
    created_date timestamp
);

CREATE TABLE IF NOT EXISTS products (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference      varchar(50),
    name           varchar(100),
    description    varchar(255),
    category_id    bigint,
    stock_quantity integer,
    min_threshold  integer,
    unit_price     double precision,
    created_date   timestamp,
    updated_date   timestamp
);

CREATE TABLE IF NOT EXISTS suppliers (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nif          varchar(50),
    name         varchar(100),
    phone        varchar(20),
    address      varchar(255),
    created_date timestamp
);

CREATE TABLE IF NOT EXISTS stock_movements (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         bigint,
    type               varchar(10),
    supplier_id        bigint,
    recipient          varchar(150),
    quantity           integer,
    reason             varchar(255),
    external_reference varchar(100),
    unit_price         double precision,
    user_id            bigint,
    reverses_id        bigint,
    movement_date      timestamp
);

-- 2. Colonnes manquantes : ajout + valeur par défaut + contrainte NOT NULL ---

CREATE OR REPLACE FUNCTION _ensure_col(
    p_table text, p_col text, p_type text, p_default text, p_not_null boolean
) RETURNS void LANGUAGE plpgsql AS $fn$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = p_table AND column_name = p_col
    ) THEN
        EXECUTE format('ALTER TABLE %I ADD COLUMN %I %s', p_table, p_col, p_type);
    END IF;
    IF p_default IS NOT NULL THEN
        EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET DEFAULT %s', p_table, p_col, p_default);
        EXECUTE format('UPDATE %I SET %I = %s WHERE %I IS NULL', p_table, p_col, p_default, p_col);
    END IF;
    IF p_not_null THEN
        EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET NOT NULL', p_table, p_col);
    END IF;
END
$fn$;

