-- 3. Clés étrangères (idempotent, identification par relations) ---------------

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'products'::regclass
          AND confrelid = 'categories'::regclass
    ) THEN
        ALTER TABLE products ADD CONSTRAINT fk_products_category
            FOREIGN KEY (category_id) REFERENCES categories (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'stock_movements'::regclass
          AND confrelid = 'products'::regclass
          AND pg_get_constraintdef(oid) LIKE '%(product_id)%'
    ) THEN
        ALTER TABLE stock_movements ADD CONSTRAINT fk_movements_product
            FOREIGN KEY (product_id) REFERENCES products (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'stock_movements'::regclass
          AND confrelid = 'suppliers'::regclass
    ) THEN
        ALTER TABLE stock_movements ADD CONSTRAINT fk_movements_supplier
            FOREIGN KEY (supplier_id) REFERENCES suppliers (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'stock_movements'::regclass
          AND confrelid = 'users'::regclass
          AND pg_get_constraintdef(oid) LIKE '%(user_id)%'
    ) THEN
        ALTER TABLE stock_movements ADD CONSTRAINT fk_movements_user
            FOREIGN KEY (user_id) REFERENCES users (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'stock_movements'::regclass
          AND confrelid = 'stock_movements'::regclass
    ) THEN
        ALTER TABLE stock_movements ADD CONSTRAINT fk_movements_reverses
            FOREIGN KEY (reverses_id) REFERENCES stock_movements (id);
    END IF;
END $$;

-- 4. Uniques (présence d'un index sur la colonne, indépendamment du nom) -----

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = 'public' AND tablename = 'users'
          AND indexdef LIKE '%(username)%'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT uq_users_username UNIQUE (username);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = 'public' AND tablename = 'products'
          AND indexdef LIKE '%(reference)%'
    ) THEN
        ALTER TABLE products ADD CONSTRAINT uq_products_reference UNIQUE (reference);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = 'public' AND tablename = 'categories'
          AND indexdef LIKE '%(name)%'
    ) THEN
        ALTER TABLE categories ADD CONSTRAINT uq_categories_name UNIQUE (name);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = 'public' AND tablename = 'suppliers'
          AND indexdef LIKE '%(nif)%'
    ) THEN
        ALTER TABLE suppliers ADD CONSTRAINT uq_suppliers_nif UNIQUE (nif);
    END IF;
END $$;

